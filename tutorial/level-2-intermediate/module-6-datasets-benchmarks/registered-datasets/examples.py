"""
Helper module: CLI examples and explanations for registered datasets.
"""


def show_dataset_download() -> None:
    """Demonstrate the harbor dataset download command."""
    print("=" * 60)
    print("Step 5: Downloading Datasets")
    print("=" * 60)
    print()
    print("You can also download datasets explicitly for inspection:")
    print()
    print("  # Download to current directory (export mode)")
    print("  harbor dataset download my-dataset")
    print()
    print("  # Download a specific version")
    print("  harbor dataset download my-dataset@v1.0")
    print()
    print("  # Download to a custom directory")
    print("  harbor dataset download my-dataset -o ./benchmarks/")
    print()
    print("  # Cache mode (content-addressable under ~/.cache/harbor)")
    print("  harbor dataset download my-dataset --cache")
    print()
    print("Export mode is useful for inspecting task files, modifying")
    print("tasks, or using them as templates for your own datasets.")
    print()


def show_run_examples() -> None:
    """Show example commands for running registered datasets."""
    print("=" * 60)
    print("Step 6: Running Registered Datasets")
    print("=" * 60)
    print()
    print("Here are common patterns for running registered datasets.")
    print("Note: these commands require the datasets to exist in the")
    print("registry and may require specific API keys or configurations.")
    print()
    print("  # Run with a specific agent and model")
    print('  harbor run -d "harbor/hello-world" \\')
    print('    -a claude-code \\')
    print('    -m "anthropic/claude-sonnet-4-5-20250929"')
    print()
    print("  # Run with cloud environments for parallel execution")
    print('  harbor run -d "swe-bench/verified" \\')
    print('    -a claude-code \\')
    print('    -m "anthropic/claude-sonnet-4-5-20250929" \\')
    print('    -e daytona -n 32')
    print()
    print("  # Run with the oracle agent to validate a dataset")
    print('  harbor run -d "harbor/hello-world" -a oracle')
    print()
    print("  # Use a git-based registry")
    print('  harbor run -d "my-org/my-dataset" \\')
    print('    --repo "github.com/my-org/my-registry" \\')
    print('    -a oracle')
    print()


def show_job_config_example() -> None:
    """Show how to reference registered datasets in job.yaml."""
    print("=" * 60)
    print("Step 7: Registered Datasets in job.yaml")
    print("=" * 60)
    print()
    print("You can reference registered datasets in a job.yaml config:")
    print()
    print("  # job.yaml with a registered dataset")
    print("  datasets:")
    print('    - name: "harbor/hello-world"')
    print()
    print("  # job.yaml with a local dataset")
    print("  datasets:")
    print("    - path: ./my-tasks")
    print()
    print("  # job.yaml with multiple datasets")
    print("  datasets:")
    print('    - name: "harbor/hello-world"')
    print("    - path: ./my-custom-tasks")
    print()
    print("  agents:")
    print("    - name: claude-code")
    print('      model_name: "anthropic/claude-sonnet-4-5-20250929"')
    print()
    print("  environment:")
    print("    type: docker")
    print("    delete: true")
    print()
    print("Then run with: harbor run -c job.yaml")
    print()
